export function getThresholdMetrics(rawThreshold) {
  const threshold = Number(rawThreshold)
  if (!Number.isFinite(threshold) || threshold <= 0) {
    return { precision: 0.1512, recall: 0.6005, f1: 0.2416 }
  }
  if (threshold <= calibrationPoints[0].threshold) {
    const first = calibrationPoints[0]
    return { precision: first.precision, recall: first.recall, f1: first.f1 }
  }
  const last = calibrationPoints[calibrationPoints.length - 1]
  if (threshold >= last.threshold) {
    return { precision: last.precision, recall: last.recall, f1: last.f1 }
  }
  for (let i = 0; i < calibrationPoints.length - 1; i += 1) {
    const p1 = calibrationPoints[i]
    const p2 = calibrationPoints[i + 1]
    if (threshold >= p1.threshold && threshold <= p2.threshold) {
      const factor = (threshold - p1.threshold) / (p2.threshold - p1.threshold)
      return {
        precision: p1.precision + factor * (p2.precision - p1.precision),
        recall: p1.recall + factor * (p2.recall - p1.recall),
        f1: p1.f1 + factor * (p2.f1 - p1.f1),
      }
    }
  }
  return { precision: 0.1512, recall: 0.6005, f1: 0.2416 }
}
